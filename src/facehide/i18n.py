_lang = "zh"


def normalize_language(value: Any) -> str:
    raw = str(value or "zh").strip().lower().replace("_", "-")
    if raw.startswith("en"):
        return "en"
    return "zh"


def current_language() -> str:
    return _lang


def set_language(value: Any) -> str:
    global _lang
    _lang = normalize_language(value)
    return _lang


def t(key: str, **kwargs: Any) -> str:
    table = _STRINGS.get(_lang) or _STRINGS["zh"]
    text = table.get(key) or _STRINGS["zh"].get(key) or key
    if kwargs:
        return text.format(**kwargs)
    return text
